
-- =========================================
-- MERIT-CORE: Core database tables
-- =========================================

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role VARCHAR(30) NOT NULL DEFAULT 'student'
        CHECK (role IN (
            'student',
            'graduate',
            'employer',
            'university_admin',
            'platform_admin'
        )),
    is_verified BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    organization_type VARCHAR(30) NOT NULL
        CHECK (organization_type IN (
            'employer',
            'university',
            'training_provider',
            'other'
        )),
    description TEXT,
    website TEXT,
    email VARCHAR(255),
    is_verified BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =========================================
-- OPPORTUNITIES
-- =========================================

CREATE TABLE IF NOT EXISTS opportunities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL
        REFERENCES organizations(id) ON DELETE RESTRICT,
    title VARCHAR(250) NOT NULL,
    description TEXT NOT NULL,
    opportunity_type VARCHAR(50) NOT NULL,
    location VARCHAR(250),
    application_url TEXT,
    deadline TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_opportunities_organization
    ON opportunities(organization_id);

CREATE INDEX IF NOT EXISTS idx_opportunities_deadline
    ON opportunities(deadline);


-- =========================================
-- SAVED OPPORTUNITIES
-- =========================================

CREATE TABLE IF NOT EXISTS saved_opportunities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    opportunity_id BIGINT NOT NULL
        REFERENCES opportunities(id) ON DELETE CASCADE,
    saved_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_saved_user_opportunity
        UNIQUE (user_id, opportunity_id)
);


-- =========================================
-- REMINDERS
-- =========================================

CREATE TABLE IF NOT EXISTS reminders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    opportunity_id BIGINT NOT NULL
        REFERENCES opportunities(id) ON DELETE CASCADE,
    remind_at TIMESTAMPTZ NOT NULL,
    is_sent BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_reminders_user
    ON reminders(user_id);

CREATE INDEX IF NOT EXISTS idx_reminders_due
    ON reminders(remind_at)
    WHERE is_sent = FALSE;


-- Student and graduate profile information
CREATE TABLE IF NOT EXISTS student_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL UNIQUE
        REFERENCES users(id) ON DELETE CASCADE,

    biography TEXT,
    institution_name VARCHAR(200),
    degree_name VARCHAR(200),
    field_of_study VARCHAR(200),
    graduation_year INTEGER,
    skills_summary TEXT,
    career_interests TEXT,
    profile_photo_url TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT valid_graduation_year
        CHECK (
            graduation_year IS NULL
            OR graduation_year BETWEEN 1950 AND 2150
        )
);

CREATE INDEX IF NOT EXISTS idx_student_profiles_institution
    ON student_profiles(institution_name);
